/**
 * A GRN is one commodity in one chamber, so an outward movement withdraws bags from that GRN's
 * available balance.
 * Delivery requires bags to deliver (either as quantity or composition).
 */
export const createDeliverySchema = z
  .object({
    grnId: z.string().trim().min(1, 'grnId is required'),
    date: z.coerce.date().default(() => new Date()),
    quantity: z.number().int().positive('Quantity must be positive').max(100000).nullish(),
    smallBags: z
      .number({ invalid_type_error: 'Small bags must be a number' })
      .int('Small bags must be a whole number')
      .min(0, 'Small bags cannot be negative')
      .max(100000, 'Small bags cannot exceed 100,000')
      .default(0),
    bigBags: z
      .number({ invalid_type_error: 'Big bags must be a number' })
      .int('Big bags must be a whole number')
      .min(0, 'Big bags cannot be negative')
      .max(100000, 'Big bags cannot exceed 100,000')
      .default(0),
    marks: z.string().trim().max(100).nullish(),
    /** Gate pass number. Optional on API (auto-generated by counter when omitted); required on UI dispatch form. */
    gpNumber: z.string().trim().max(100).nullish(),
    /** Vehicle registration number in normalized Indian format. Optional on API; required on UI dispatch form. */
    vehicleNumber: indianVehicleSchema.nullish(),
    /** Driver name for physical gate clearance. Optional on API; required on UI dispatch form. */
    driverName: z.string().trim().max(100).nullish(),
    weight: z.number().positive('weight must be positive').nullish(),
    remarks: z.string().trim().max(500).nullish(),
    bagType: bagTypeSchema.nullish(),
    bagCategory: outwardBagCategorySchema.nullish(),
    bagPrice: bagPriceSchema.nullish(),
    seasonalBagPrice: bagPriceSchema.nullish(),
    monthlyBagPrice: bagPriceSchema.nullish(),
    rentCharge: z.number().min(0).nullish(),
    paymentAmount: z.number().min(0, 'Payment amount cannot be negative').nullish(),
    paymentMode: paymentModeSchema.nullish(),
    paymentReference: z.string().trim().max(100).nullish(),
    idempotencyKey: z.string().trim().min(1).max(100).nullish(),
    unclassifiedDispatch: unclassifiedDispatchAllocationSchema.nullish(),
    confirmedDispatch: confirmedDispatchAllocationSchema.nullish(),
  })
  .refine(
    (data) => {
      const uCount = data.unclassifiedDispatch
        ? (data.unclassifiedDispatch.quantity ?? ((data.unclassifiedDispatch.smallBags ?? 0) + (data.unclassifiedDispatch.bigBags ?? 0)))
        : 0;
      const cCount = data.confirmedDispatch
        ? (data.confirmedDispatch.quantity ?? ((data.confirmedDispatch.smallBags ?? 0) + (data.confirmedDispatch.bigBags ?? 0)))
        : 0;
      return (
        uCount + cCount > 0 ||
        (data.quantity != null && data.quantity > 0) ||
        data.smallBags + data.bigBags > 0
      );
    },
    {
      message: 'Delivery must move at least one bag',
      path: ['smallBags'],
    },
  )
  .refine(
    (data) => {
      const maxFutureAllowed = new Date(Date.now() + 5 * 60 * 1000);
      return data.date <= maxFutureAllowed;
    },
    {
      message: 'Delivery date cannot be in the future',
      path: ['date'],
    },
  );

export type CreateDeliveryInput = z.input<typeof createDeliverySchema>;
export type CreateDeliveryDTO = z.infer<typeof createDeliverySchema>;

